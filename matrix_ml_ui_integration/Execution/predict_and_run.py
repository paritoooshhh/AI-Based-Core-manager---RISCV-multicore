import subprocess, sys
from pathlib import Path
from sklearn.tree import DecisionTreeClassifier
import pandas as pd

ROOT = Path(__file__).resolve().parent
N = int(sys.argv[1]) if len(sys.argv)>1 else 4
if N < 1 or N > 16:
    raise SystemExit("Choose matrix size N from 1 to 16.")

# Build a small training table from the same declared cycle model:
# cycles = ceil(N / cores) * N^2 + 8 * (cores - 1)
# Labels choose minimum modeled cycles; ties prefer fewer cores.
rows = []
for n in range(1, 17):
    candidate_cycles = {c: ((n + c - 1)//c) * n*n + 8*(c-1) for c in (1,2,4)}
    best = min((cyc, cores) for cores, cyc in candidate_cycles.items())[1]
    for cores in (1,2,4):
        rows.append({"matrix_size": n, "operations": n**3,
                     "candidate_cores": cores, "candidate_cycles": candidate_cycles[cores],
                     "best_core_label": best})
training = pd.DataFrame(rows)
X = training[["matrix_size", "operations"]]
y = training["best_core_label"]
model = DecisionTreeClassifier(max_depth=3, random_state=42)
# one row per matrix size to avoid weighting a size 3 times
model.fit(X.drop_duplicates().assign(operations=lambda d: d["matrix_size"]**3),
          training.drop_duplicates("matrix_size")["best_core_label"])
prediction = int(model.predict(pd.DataFrame([{"matrix_size":N,"operations":N**3}]))[0])
print(f"MODEL_TYPE,DecisionTreeClassifier")
print(f"TRAINING_SWEEP,matrix_sizes=1..16,core_options=1|2|4,rows={len(training)}")
print(f"MODEL_PREDICTION,matrix_size={N},selected_cores={prediction}")
print("MODEL_SCOPE,trained on synthetic labels generated by the declared cycle model; not the previously trained project model.")

exe = ROOT / "matrix_demo.vvp"
if not exe.exists():
    raise SystemExit("Missing matrix_demo.vvp. Run .\\run_matrix_demo.ps1 first.")

results = {}
for cores in (1,2,4):
    p = subprocess.run(["vvp", str(exe), f"+N={N}", f"+CORES={cores}"],
                       capture_output=True, text=True)
    output = p.stdout + p.stderr
    print(f"\n--- Candidate: {cores} core(s) ---")
    print(output, end="")
    cyc = None
    for line in output.splitlines():
        if line.startswith("SIMULATED_CYCLES="):
            cyc = int(line.split("=",1)[1])
    if "DEMO_STATUS,PASS" not in output or cyc is None:
        raise SystemExit("Simulation failed or output could not be parsed.")
    results[cores] = cyc

print("\nCANDIDATE_SUMMARY")
for cores, cyc in results.items():
    print(f"cores={cores},cycles={cyc}")
print(f"PREDICTED_CONFIGURATION,cores={prediction},cycles={results[prediction]}")
print("INTERPRETATION: modeled cycles include a fixed 8-cycle coordination overhead per additional core. These are simulation-model estimates, not physical CPU measurements.")
